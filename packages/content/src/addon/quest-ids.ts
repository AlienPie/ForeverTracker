import { eq } from "drizzle-orm";
import { contentRecord, type Db } from "@ft/db";

const IDS_PER_LINE = 12;

const SAFE_BUILD = /^[0-9A-Za-z._-]{1,40}$/;

/** The build ends up in a Lua comment: anything unexpected becomes "unknown". */
function safeBuild(build: unknown): string {
  return typeof build === "string" && SAFE_BUILD.test(build) && !build.includes("--") ? build : "unknown";
}

/** Render the Lua 5.1 file that hands the bundled quest ID list to the addon. */
export function renderQuestIdsLua(ids: number[], build: string): string {
  const clean = [...new Set(ids.filter((n) => Number.isInteger(n) && n >= 0))].sort((a, b) => a - b);
  const header = [
    "-- Quest ID list for ForeverTracker.",
    "-- Data from ForeverDB.net (https://foreverdb.net)",
    "-- GENERATED by `pnpm addon:quest-ids`. Do not edit by hand.",
    `-- Game build: ${safeBuild(build)}`,
    `-- Count: ${clean.length}`,
    "",
  ];
  if (clean.length === 0) return [...header, "FT.setQuestIdList({})", ""].join("\n");
  const rows: string[] = [];
  for (let i = 0; i < clean.length; i += IDS_PER_LINE) {
    rows.push("  " + clean.slice(i, i + IDS_PER_LINE).join(", ") + ",");
  }
  return [...header, "FT.setQuestIdList({", ...rows, "})", ""].join("\n");
}

/** Read every quest ID (and the build they were synced at) from the content mirror. */
export function readQuestIds(db: Db): { ids: number[]; build: string | null } {
  const rows = db
    .select({ data: contentRecord.data, build: contentRecord.build })
    .from(contentRecord)
    .where(eq(contentRecord.resource, "quests"))
    .all();
  if (rows.length === 0) {
    throw new Error("No quest records in the content mirror: run `pnpm content:sync` first");
  }
  const ids: number[] = [];
  for (const r of rows) {
    const id = (JSON.parse(r.data) as { id?: unknown } | null)?.id;
    if (typeof id === "number") ids.push(id);
  }
  ids.sort((a, b) => a - b);
  return { ids, build: rows[0]?.build ?? null };
}
